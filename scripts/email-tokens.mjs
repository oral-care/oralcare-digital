// Writes src/lib/email/tokens.ts from the token files (plan 4.14 and 13.2).
// E-mail clients don't read CSS variables, so the e-mails need the values
// themselves. Run it after the tokens change: node scripts/email-tokens.mjs.
// `--check` fails instead of writing when the file is out of date (CI).
import { readFileSync, writeFileSync } from "node:fs";

const SOURCES = ["src/styles/oralcare-tokens.css", "src/styles/app-tokens.css"];
const TARGET = "src/lib/email/tokens.ts";

// What each e-mail colour is in the design system.
const COLOURS = {
  text: "--foreground",
  muted: "--muted-foreground",
  body: "--color-oc-neutral-700",
  border: "--border",
  page: "--background",
  card: "--card",
  panel: "--secondary",
  attention: "--color-oc-orange-400",
  attentionText: "--attention-text",
  button: "--primary",
  buttonText: "--primary-foreground",
};

const declarations = new Map();
for (const file of SOURCES) {
  const css = readFileSync(file, "utf8").replace(/\/\*[\s\S]*?\*\//g, "");
  for (const [, name, value] of css.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)) {
    // The first declaration is the light theme, which is what e-mails use.
    if (!declarations.has(name)) declarations.set(name, value.trim());
  }
}

function resolve(name, seen = new Set()) {
  if (seen.has(name)) throw new Error(`Token loop at ${name}`);
  const value = declarations.get(name);
  if (value === undefined) throw new Error(`Token ${name} is missing`);
  const reference = /^var\((--[\w-]+)\)$/.exec(value);
  return reference ? resolve(reference[1], seen.add(name)) : value;
}

const lines = Object.entries(COLOURS).map(([key, token]) => {
  const value = resolve(token);
  if (!/^#[0-9a-f]{6}$/i.test(value)) throw new Error(`${token} is ${value}, not a hex colour`);
  return `  /** ${token} */\n  ${key}: "${value.toLowerCase()}",`;
});

const output = `// Generated by scripts/email-tokens.mjs from the token files. Don't edit.
// E-mail clients don't read CSS variables, so the e-mails use these values.

export const emailColours = {
${lines.join("\n")}
} as const;

/** Inter as in the app, with the fonts every e-mail client has. */
export const emailFont = "Inter, Arial, Helvetica, sans-serif";
`;

if (process.argv.includes("--check")) {
  if (readFileSync(TARGET, "utf8") !== output) {
    console.error(`${TARGET} is out of date. Run node scripts/email-tokens.mjs.`);
    process.exit(1);
  }
} else {
  writeFileSync(TARGET, output);
}
